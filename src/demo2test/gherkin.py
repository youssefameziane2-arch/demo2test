"""Étape 4 : génération du scénario Gherkin et du rapport de relecture."""
from __future__ import annotations

import json
import re
from dataclasses import asdict, dataclass
from pathlib import Path

from .abstraction.actions import Recording, group_events
from .abstraction.assertions import Assertion, suggest
from .abstraction.matching import MatchResult, Pipeline
from .catalog import BY_ID
from .recorder.trace import RawEvent


@dataclass
class Generated:
    feature: str
    report: dict
    recording: Recording
    result: MatchResult
    assertions: list[Assertion]


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_") or "scenario"


def render_feature(name: str, rec: Recording, result: MatchResult,
                   assertions: list[Assertion], trace_name: str = "") -> str:
    lines = [
        "# language: en",
        f"# Generated by demo2test from {trace_name or 'a recorded demo'} - review before merging.",
        f"# {rec.n_raw_events} raw events -> {len(rec.actions)} UI actions -> "
        f"{len(result.calls)} steps + {len(assertions)} checks",
        f"Feature: {name}",
        "",
        f"  Scenario: {name}",
        "    Given the NoC Config Studio is open",
    ]
    by_call: dict[int, list[Assertion]] = {}
    for a in assertions:
        by_call.setdefault(a.after_call, []).append(a)

    def then_lines(idx: int) -> list[str]:
        out = []
        for a in by_call.get(idx, []):
            text = BY_ID[a.step_id].render(**a.params)
            tag = a.origin + (f", observed after {a.observed_delay_ms} ms"
                              if a.observed_delay_ms else "")
            out.append(f"    # {tag}")
            out.append(f"    Then {text}")
        return out

    lines += then_lines(-1)
    for idx, call in enumerate(result.calls):
        comment = call.source if call.source in ("rule", "generic") else \
            f"{call.source}, confidence {call.confidence:.2f}"
        lines.append(f"    # {comment}" + (f" ({call.note})" if call.note else ""))
        lines.append(f"    When {call.text}")
        lines += then_lines(idx)
    # Gherkin : « And » pour les mots-clés répétés
    out, prev = [], None
    for line in lines:
        m = re.match(r"(\s+)(Given|When|Then) (.*)", line)
        if m and m.group(2) == prev:
            line = f"{m.group(1)}And {m.group(3)}"
        if m:
            prev = m.group(2)
        out.append(line)
    return "\n".join(out) + "\n"


def build_report(rec: Recording, result: MatchResult, assertions, pipeline: Pipeline) -> dict:
    sources = {}
    for c in result.calls:
        sources[c.source] = sources.get(c.source, 0) + 1
    return {
        "pipeline": pipeline.name,
        "raw_events": rec.n_raw_events,
        "ui_actions": len(rec.actions),
        "steps": [{"text": c.text, "id": c.step_id, "source": c.source,
                   "confidence": c.confidence, "covers": [rec.actions[i].short() for i in c.covered],
                   "note": c.note} for c in result.calls],
        "steps_by_source": sources,
        "ignored_actions": [rec.actions[i].short() for i in result.ignored],
        "assertions": [asdict(a) for a in assertions],
        "llm_calls": result.llm_calls,
        "llm_rejections": result.llm_rejections,
    }


def generate(events: list[RawEvent], name: str, pipeline: Pipeline,
             assertions_mode: str = "key", trace_name: str = "") -> Generated:
    rec = group_events(events)
    result = pipeline.run(rec)
    checks = suggest(rec, result, assertions_mode)
    feature = render_feature(name, rec, result, checks, trace_name)
    return Generated(feature, build_report(rec, result, checks, pipeline), rec, result, checks)


def write_outputs(gen: Generated, out_dir: str | Path, name: str) -> tuple[Path, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    feature = out_dir / f"{_slug(name)}.feature"
    report = out_dir / f"{_slug(name)}.review.json"
    feature.write_text(gen.feature, encoding="utf-8")
    report.write_text(json.dumps(gen.report, indent=2, ensure_ascii=False), encoding="utf-8")
    return feature, report
